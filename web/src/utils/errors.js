export function explain(err, fallback = '操作失败') {
  if (!err) return fallback
  if (err.code != null && ERROR_TEXT[err.code]) return ERROR_TEXT[err.code]
  return err.message || fallback
}

export function fieldErrors(err) {
  const list = err?.data?.field_errors
  return Array.isArray(list) ? list : []
}
